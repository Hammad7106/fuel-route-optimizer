"""Offline geocoding of US place names.

Names are resolved against a prebuilt index of US places
(``data/us_places.csv.gz``, generated by ``manage.py build_places``), so
geocoding never calls an external API.
"""

from __future__ import annotations

import csv
import gzip
import re
import unicodedata
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from django.conf import settings

PLACE_INDEX_FIELDS = ("state", "key", "name", "latitude", "longitude")

_ABBREVIATIONS = (
    (re.compile(r"\bST\b"), "SAINT"),
    (re.compile(r"\bSTE\b"), "SAINTE"),
    (re.compile(r"\bFT\b"), "FORT"),
    (re.compile(r"\bMT\b"), "MOUNT"),
)
_NON_ALPHANUMERIC = re.compile(r"[^A-Z0-9]+")


@dataclass(frozen=True, slots=True)
class Coordinates:
    latitude: float
    longitude: float


@dataclass(frozen=True, slots=True)
class Place:
    name: str
    state: str
    coordinates: Coordinates


def normalize_place_name(name: str) -> str:
    """Return the key used to compare place names.

    Accents, case, punctuation and spacing are ignored and common
    abbreviations are expanded, so "Mc Calla" matches "McCalla" and
    "St. Louis" matches "Saint Louis".
    """
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    key = ascii_name.upper().replace("'", "").replace(".", " ")
    for pattern, replacement in _ABBREVIATIONS:
        key = pattern.sub(replacement, key)
    return _NON_ALPHANUMERIC.sub("", key)


class PlaceIndex:
    """In-memory lookup of US places by (state, normalized name)."""

    def __init__(self, places: dict[tuple[str, str], Place]) -> None:
        self._places = places

    @classmethod
    def from_file(cls, path: Path) -> PlaceIndex:
        with gzip.open(path, "rt", encoding="utf-8", newline="") as file:
            places = {
                (row["state"], row["key"]): Place(
                    name=row["name"],
                    state=row["state"],
                    coordinates=Coordinates(float(row["latitude"]), float(row["longitude"])),
                )
                for row in csv.DictReader(file)
            }
        return cls(places)

    def __len__(self) -> int:
        return len(self._places)

    def lookup(self, city: str, state: str) -> Place | None:
        return self._places.get((state.strip().upper(), normalize_place_name(city)))


@lru_cache(maxsize=1)
def get_place_index() -> PlaceIndex:
    """Return the process-wide place index, loading it on first use."""
    return PlaceIndex.from_file(settings.US_PLACES_FILE)
